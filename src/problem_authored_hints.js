  const list = window.BUZZ_PROBLEMS || [];
  let applied = 0;
  const blocked = window.BuzzCannedHints;
  const visibleHints = (problem) => {
    if (!Array.isArray(problem.hints)) return 0;
    return problem.hints.filter((hint) => {
      if (!String(hint || "").trim()) return false;
      return !(blocked && blocked.isCanned(hint));
    }).length;
  };
  list.forEach((problem) => {
    const hints = HINTS[problem.id];
    // 只補「實際看不到任何作者提示」的題：完全沒寫的，以及寫了但全是
    // 罐頭（authoredHints 會濾掉、使用者看到的是零）的。
    // 真正有內容的作者提示永遠不覆蓋。
    if (!hints || visibleHints(problem) > 0) return;
    problem.hints = hints.slice();
    applied += 1;
  });

